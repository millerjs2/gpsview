"""Every formatter output is compared with the output of gpsd's own C code.

tests/golden_fmt.tsv is generated by tools/golden/gen_golden.sh, which compiles the
functions from the gpsd tree. Regenerate it there, not by hand.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from gpsview import fmt

GOLDEN = Path(__file__).with_name("golden_fmt.tsv")


def _cases():
    out = []
    for line in GOLDEN.read_text(encoding="utf-8").splitlines():
        if not line:
            continue
        fields = line.split("\t")
        out.append(pytest.param(fields, id=f"{fields[0]}:{fields[1:-1][:2]}"))
    return out


def _f(s: str) -> float:
    return float(s)


def _opt(s: str) -> str | None:
    return None if s == "-" else s


DEG_KIND = {"0": fmt.DD, "1": fmt.DDMM, "2": fmt.DDMMSS}


@pytest.mark.parametrize("fields", _cases())
def test_matches_gpsd_c(fields):
    name = fields[0]
    if name == "deg_to_str2":
        _, kind, f, sp, sn, want = fields
        got = fmt.deg_to_str(DEG_KIND[kind], _f(f), _opt(sp), _opt(sn))
    elif name == "maidenhead":
        _, lat, lon, want = fields
        got = fmt.maidenhead(_f(lat), _f(lon))
    elif name == "ep_to_str":
        _, ep, factor, units, want = fields
        got = fmt.ep_to_str(_f(ep), _f(factor), units)
    elif name == "dop_to_str":
        _, dop, want = fields
        got = fmt.dop_to_str(_f(dop))
    elif name == "tenth_to_str":
        _, v, lo, hi, want = fields
        got = fmt.tenth_to_str(_f(v), _f(lo), _f(hi))
    elif name == "int_to_str":
        _, v, lo, hi, want = fields
        got = fmt.int_to_str(int(v), int(lo), int(hi))
    elif name == "ecef_to_str":
        _, pos, vel, units, want = fields
        # the C global altfactor is a float: METERS_TO_FEET rounded to 32 bits for feet
        factor = fmt.f32(fmt.METERS_TO_FEET) if units == "ft" else 1.0
        got = fmt.ecef_to_str(_f(pos), _f(vel), factor, units)
    else:
        raise AssertionError(f"unknown golden case {name}")
    assert got == want


def test_golden_file_has_cases():
    # guard against an empty or truncated generated file
    assert len(_cases()) > 200
